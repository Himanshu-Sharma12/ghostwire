"""Mock API Server generator module for GhostWire.
Synthesizes a standalone, executable FastAPI mock server serving captured payload fixtures.
"""

import json
from pathlib import Path
from typing import List, Optional
from ..core.models import AuthInfo, EndpointModel


class MockServerGenerator:
    def __init__(self, app_title: str = "GhostWire Mock API"):
        self.app_title = app_title

    def generate_code(self, endpoints: List[EndpointModel], auth: Optional[AuthInfo] = None) -> str:
        """Generates executable FastAPI mock server code."""
        lines = [
            '"""',
            'Auto-generated FastAPI Mock Server generated by GhostWire.',
            'Run directly with: python mock_server.py',
            'Interactive Swagger Docs available at http://localhost:8000/docs',
            '"""',
            '',
            'from typing import Any, Dict, Optional',
            'from fastapi import FastAPI, Request, Response, status',
            'import uvicorn',
            '',
            f'app = FastAPI(title="{self.app_title}", version="1.0.0",',
            '              description="Local replica mock server generated from reverse-engineered traffic.")',
            '',
            '@app.get("/health")',
            'def health_check():',
            '    return {"status": "ok", "mock_server": "GhostWire Active"}',
            '',
        ]

        seen_ops = set()
        for ep in endpoints:
            op_name = f"mock_{ep.operation_id}"
            if op_name in seen_ops:
                counter = 1
                while f"{op_name}_{counter}" in seen_ops:
                    counter += 1
                op_name = f"{op_name}_{counter}"
            seen_ops.add(op_name)

            # Determine response fixture
            sample_response = {}
            status_code = 200
            if ep.responses:
                # pick lowest status code (usually 200/201)
                status_code = min(ep.responses.keys())
                sample_response = ep.responses[status_code].example_body

            fixture_str = json.dumps(sample_response, indent=4) if sample_response is not None else "{}"

            method_lower = ep.method.lower()
            decorator = f'@app.{method_lower}("{ep.path}", status_code={status_code}, summary="{ep.summary}")'
            lines.append(decorator)
            lines.append(f"async def {op_name}(request: Request):")
            lines.append(f'    """Mock response for {ep.method} {ep.path}"""')
            lines.append(f"    return {fixture_str}")
            lines.append("")

        lines.extend([
            'if __name__ == "__main__":',
            '    print("👻 GhostWire Mock API Server starting on http://localhost:8000 ...")',
            '    print("📖 Interactive Docs: http://localhost:8000/docs")',
            '    uvicorn.run(app, host="0.0.0.0", port=8000)',
            ''
        ])

        return "\n".join(lines)

    def export_file(self, endpoints: List[EndpointModel], auth: Optional[AuthInfo], 
                    output_dir: Path) -> Path:
        """Exports the generated mock_server.py."""
        output_dir.mkdir(parents=True, exist_ok=True)
        code = self.generate_code(endpoints, auth)
        file_path = output_dir / "mock_server.py"
        with open(file_path, "w", encoding="utf-8") as f:
            f.write(code)
        return file_path
