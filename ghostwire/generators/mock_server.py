"""Mock API Server generator module for GhostWire.
Synthesizes a standalone, executable FastAPI mock server serving captured payload fixtures.
"""

from pathlib import Path
from typing import Any, Dict, List, Optional, Set, Tuple
from ..core.models import AuthInfo, EndpointModel
from .naming import python_doc_text, python_identifier


def response_fixture(ep: EndpointModel) -> Tuple[int, Any]:
    """Picks the lowest observed status code (usually 200/201) and its captured body."""
    if not ep.responses:
        return 200, {}
    status_code = min(ep.responses.keys())
    return status_code, ep.responses[status_code].example_body


class MockServerGenerator:
    def __init__(self, app_title: str = "GhostWire Mock API"):
        self.app_title = app_title

    def generate_code(self, endpoints: List[EndpointModel], auth: Optional[AuthInfo] = None) -> str:
        """Generates executable FastAPI mock server code."""
        lines = [
            '"""',
            'Auto-generated FastAPI Mock Server generated by GhostWire.',
            'Run directly with: python mock_server.py [--port 8000]',
            'Interactive Swagger Docs available at http://localhost:8000/docs',
            '"""',
            '',
            'import re',
            'import sys',
            'from typing import Any, Dict',
            'from fastapi import FastAPI, Request, Response',
            'from fastapi.middleware.cors import CORSMiddleware',
            'from fastapi.responses import JSONResponse',
            'import uvicorn',
            '',
            f'app = FastAPI(title={self.app_title!r}, version="1.0.0",',
            '              description="Local replica mock server generated from reverse-engineered traffic.")',
            'app.add_middleware(CORSMiddleware, allow_origins=["*"], allow_methods=["*"], allow_headers=["*"])',
            '',
            '',
            'def fixture(status_code: int, body: Any) -> Response:',
            '    if status_code == 204:',
            '        return Response(status_code=204)',
            '    return JSONResponse(content=body, status_code=status_code)',
            '',
            '',
            '@app.get("/health")',
            'def health_check():',
            '    return {"status": "ok", "mock_server": "GhostWire Active"}',
            '',
        ]

        # GraphQL operations share one URL, so they are grouped behind a single dispatching route
        routes: Dict[Tuple[str, str], List[EndpointModel]] = {}
        for ep in endpoints:
            routes.setdefault((ep.method.upper(), ep.path), []).append(ep)

        # Static routes must be registered before parameterized ones (/users/me before /users/{userId})
        ordered = sorted(routes.items(), key=lambda item: (item[0][1].count("{"), item[0][1], item[0][0]))

        if any(ep.graphql_operation for ep in endpoints):
            lines.extend([
                'def graphql_operation_name(document: Any, query_params: Any) -> Any:',
                '    """Finds the operation name from operationName or the query text (body or URL)."""',
                '    operation = query_params.get("operationName")',
                '    query_text = query_params.get("query")',
                '    if isinstance(document, dict):',
                '        operation = document.get("operationName") or operation',
                '        if isinstance(document.get("query"), str):',
                '            query_text = document["query"]',
                '    if not operation and query_text:',
                '        match = re.search(r"(?:query|mutation|subscription)\\s+([a-zA-Z0-9_]+)", query_text)',
                '        operation = match.group(1) if match else ("Anonymous" if query_text.strip() else None)',
                '    return operation',
                '',
                '',
            ])

        handler_names: Set[str] = {"health_check", "fixture", "graphql_operation_name"}
        for (method, path), group in ordered:
            operations = [ep for ep in group if ep.graphql_operation]
            if operations:
                lines.extend(self._graphql_route(method, path, group, handler_names))
            else:
                lines.extend(self._rest_route(group[0], handler_names))

        lines.extend([
            'if __name__ == "__main__":',
            '    port = int(sys.argv[sys.argv.index("--port") + 1]) if "--port" in sys.argv else 8000',
            '    print(f"👻 GhostWire Mock API Server starting on http://localhost:{port} ...")',
            '    print(f"📖 Interactive Docs: http://localhost:{port}/docs")',
            '    uvicorn.run(app, host="127.0.0.1", port=port)',
            ''
        ])

        return "\n".join(lines)

    def _rest_route(self, ep: EndpointModel, handler_names: Set[str]) -> List[str]:
        op_name = python_identifier(f"mock_{ep.operation_id}", handler_names)
        status_code, body = response_fixture(ep)
        return [
            f'@app.api_route({ep.path!r}, methods=[{ep.method.upper()!r}], summary={ep.summary!r})',
            f"async def {op_name}(request: Request):",
            f'    """Mock response for {ep.method} {python_doc_text(ep.path)}"""',
            f"    return fixture({status_code}, {body!r})",
            "",
        ]

    def _graphql_route(self, method: str, path: str, group: List[EndpointModel], handler_names: Set[str]) -> List[str]:
        op_name = python_identifier(f"mock_graphql_{path}", handler_names)
        fixtures = {}
        default = None
        for ep in group:
            entry = response_fixture(ep)
            if ep.graphql_operation:
                fixtures[ep.graphql_operation] = entry
            else:
                default = entry
        if default is None:
            default = (400, {"errors": [{"message": "Unknown operation (not present in the captured traffic)"}]})
        batch_style = next((ep.graphql_batch for ep in group if ep.graphql_batch), "plain")

        table_name = f"{op_name.upper()}_FIXTURES"
        return [
            f"{table_name}: Dict[str, Any] = {fixtures!r}",
            "",
            f'@app.api_route({path!r}, methods=[{method!r}], summary="GraphQL operations: " + ", ".join({table_name}))',
            f"async def {op_name}(request: Request):",
            f'    """Dispatches GraphQL operations captured on {method} {python_doc_text(path)} by operation name."""',
            "    body = None",
            "    if request.method != \"GET\":",
            "        try:",
            "            body = await request.json()",
            "        except ValueError:",
            "            body = None",
            "    if isinstance(body, list):",
            "        # Batched request: answer every operation, in the captured response style",
            "        results = []",
            "        for index, document in enumerate(body):",
            f"            _, result = {table_name}.get(graphql_operation_name(document, {{}}), {default!r})",
            f"            results.append({{\"index\": index, \"result\": result}} if {batch_style == 'indexed'!r} else result)",
            "        return JSONResponse(content=results)",
            f"    status_code, result = {table_name}.get(graphql_operation_name(body, request.query_params), {default!r})",
            "    return fixture(status_code, result)",
            "",
        ]

    def export_file(self, endpoints: List[EndpointModel], auth: Optional[AuthInfo],
                    output_dir: Path) -> Path:
        """Exports the generated mock_server.py."""
        output_dir.mkdir(parents=True, exist_ok=True)
        code = self.generate_code(endpoints, auth)
        file_path = output_dir / "mock_server.py"
        with open(file_path, "w", encoding="utf-8") as f:
            f.write(code)
        return file_path
