"""OpenAPI 3.1.0 specification generator module for GhostWire.
Generates compliant OpenAPI documents in JSON and YAML formats.
"""

import json
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple
import yaml

from ..core.models import AuthInfo, EndpointModel


class OpenApiGenerator:
    def __init__(self, title: str = "Discovered API", version: str = "1.0.0", description: str = ""):
        self.title = title
        self.version = version
        self.description = description or "Reverse-engineered API specification generated by GhostWire."

    def generate_spec(self, endpoints: List[EndpointModel], auth: Optional[AuthInfo] = None) -> Dict[str, Any]:
        """Synthesizes an OpenAPI 3.1.0 specification dictionary."""
        servers = []
        if endpoints:
            unique_base_urls = sorted({e.base_url for e in endpoints if e.base_url})
            for u in unique_base_urls:
                servers.append({"url": u, "description": "Discovered Host"})

        spec: Dict[str, Any] = {
            "openapi": "3.1.0",
            "info": {
                "title": self.title,
                "version": self.version,
                "description": self.description
            },
            "servers": servers or [{"url": "http://localhost:8000"}],
            "paths": {},
            "components": {
                "securitySchemes": {}
            }
        }

        # Configure Security Scheme if auth detected
        if auth and auth.auth_type != "none":
            if auth.auth_type == "bearer":
                spec["components"]["securitySchemes"]["BearerAuth"] = {
                    "type": "http",
                    "scheme": "bearer",
                    "bearerFormat": "JWT"
                }
                spec["security"] = [{"BearerAuth": []}]
            elif auth.auth_type == "api_key":
                spec["components"]["securitySchemes"]["ApiKeyAuth"] = {
                    "type": "apiKey",
                    "in": "header",
                    "name": auth.header_name or "x-api-key"
                }
                spec["security"] = [{"ApiKeyAuth": []}]
            elif auth.auth_type == "cookie":
                spec["components"]["securitySchemes"]["CookieAuth"] = {
                    "type": "apiKey",
                    "in": "cookie",
                    "name": auth.cookie_name or "session"
                }
                spec["security"] = [{"CookieAuth": []}]

        # Build paths
        for ep in endpoints:
            if ep.path not in spec["paths"]:
                spec["paths"][ep.path] = {}

            method_lower = ep.method.lower()

            operation: Dict[str, Any] = {
                "operationId": ep.operation_id,
                "summary": ep.summary,
                "description": ep.description,
                "parameters": [],
                "responses": {}
            }

            # Parameters
            for param in ep.parameters:
                operation["parameters"].append({
                    "name": param.name,
                    "in": param.location,
                    "required": param.required,
                    "description": param.description or "",
                    "schema": {
                        "type": param.param_type
                    },
                    "example": param.example
                })

            # Request Body
            if ep.request_body and ep.request_body.schema_dict:
                operation["requestBody"] = {
                    "required": True,
                    "content": {
                        ep.request_body.content_type: {
                            "schema": ep.request_body.schema_dict,
                            "example": ep.request_body.example_payload
                        }
                    }
                }

            # Responses
            if ep.responses:
                for code, res in ep.responses.items():
                    operation["responses"][str(code)] = {
                        "description": f"Observed response ({code})",
                        "content": {
                            res.content_type: {
                                "schema": res.schema_dict,
                                "example": res.example_body
                            }
                        }
                    }
            else:
                operation["responses"]["200"] = {"description": "Default success"}

            spec["paths"][ep.path][method_lower] = operation

        return spec

    def export_files(self, endpoints: List[EndpointModel], auth: Optional[AuthInfo], 
                     output_dir: Path) -> Tuple[Path, Path]:
        """Exports both openapi.json and openapi.yaml to the target directory."""
        output_dir.mkdir(parents=True, exist_ok=True)
        spec = self.generate_spec(endpoints, auth)

        json_path = output_dir / "openapi.json"
        yaml_path = output_dir / "openapi.yaml"

        with open(json_path, "w", encoding="utf-8") as f:
            json.dump(spec, f, indent=2)

        with open(yaml_path, "w", encoding="utf-8") as f:
            yaml.dump(spec, f, sort_keys=False)

        return json_path, yaml_path
